/** A lucide icon by name, or a file for one it doesn't have. */
export function Icon(props: { name: string; size?: number }) {
  return (
    <svg class="cad-model__icon" data-icon={props.name} width={props.size ?? 14} height={props.size ?? 14} viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">
      <Dynamic component={PATHS[props.name] ?? PATHS["File"]!} />
    </svg>
  );
}

/** An icon as a detached element, for DOM built without Solid, e.g. a pin over the 3D view. */
export function iconElement(name: string, size?: number): Element {
  return createRoot((dispose) => {
    const svg = (<Icon name={name} {...(size ? { size } : {})} />) as Element;
    // Static: nothing to keep tracking once it is drawn.
    dispose();
    return svg;
  });
}
